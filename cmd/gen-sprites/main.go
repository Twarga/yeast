// Command gen-sprites reads assets/sprites/pixel.json (produced by
// scripts/export-sprites.mjs from the design-system pixel.js) and emits
// internal/ui/sprites/sprites_gen.go with typed palette and frame data.
//
// Usage (from the repo root or via go generate):
//
//	go run ./cmd/gen-sprites -in assets/sprites/pixel.json -out internal/ui/sprites/sprites_gen.go
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
)

type artifact struct {
	Name    string                      `json:"name"`
	Title   string                      `json:"title"`
	Source  string                      `json:"source"`
	Cell    struct{ Width, Height int } `json:"cell"`
	Palette map[string]string           `json:"palette"`
	Frames  map[string][]string         `json:"frames"`
}

func main() {
	in := flag.String("in", "assets/sprites/pixel.json", "input sprite JSON")
	out := flag.String("out", "internal/ui/sprites/sprites_gen.go", "output Go file")
	pkg := flag.String("pkg", "sprites", "package name for generated file")
	flag.Parse()

	raw, err := os.ReadFile(*in)
	if err != nil {
		fatalf("read %s: %v", *in, err)
	}
	var a artifact
	if err := json.Unmarshal(raw, &a); err != nil {
		fatalf("parse %s: %v", *in, err)
	}
	if len(a.Palette) == 0 || len(a.Frames) == 0 {
		fatalf("%s: empty palette or frames", *in)
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by cmd/gen-sprites from %s; DO NOT EDIT.\n\n", *in)
	fmt.Fprintf(&b, "package %s\n\n", *pkg)
	fmt.Fprintf(&b, "// SpriteName is the mascot this package renders.\n")
	fmt.Fprintf(&b, "const SpriteName = %q\n\n", a.Name)
	fmt.Fprintf(&b, "// CellWidth and CellHeight are the base sprite dimensions in pixels.\n")
	fmt.Fprintf(&b, "const (\n\tCellWidth = %d\n\tCellHeight = %d\n)\n\n", a.Cell.Width, a.Cell.Height)

	writeStringMap(&b, "Palette", a.Palette, "// Palette maps one-letter pixel codes to hex colors (rrggbb).")
	writeFrameMap(&b, "Frames", a.Frames)

	names := make([]string, 0, len(a.Frames))
	for n := range a.Frames {
		names = append(names, n)
	}
	sort.Strings(names)
	fmt.Fprintf(&b, "// FrameNames lists every frame name in stable sorted order.\n")
	fmt.Fprintf(&b, "var FrameNames = []string{")
	for i, n := range names {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "%q", n)
	}
	b.WriteString("}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		fatalf("generated source does not format: %v\n%s", err, b.String())
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		fatalf("write %s: %v", *out, err)
	}
	fmt.Printf("gen-sprites: wrote %s (%d frames, %d colors)\n", *out, len(a.Frames), len(a.Palette))
}

func writeStringMap(b *bytes.Buffer, name string, m map[string]string, comment string) {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	fmt.Fprintf(b, "%s\nvar %s = map[string]string{\n", comment, name)
	for _, k := range keys {
		fmt.Fprintf(b, "\t%s: %q,\n", strconv_(k), m[k])
	}
	b.WriteString("}\n\n")
}

func writeFrameMap(b *bytes.Buffer, name string, m map[string][]string) {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	fmt.Fprintf(b, "// %s holds every named sprite frame as a grid of pixel rows.\n", name)
	fmt.Fprintf(b, "// '.' is transparent; every other byte is a Palette key.\n")
	fmt.Fprintf(b, "var %s = map[string][]string{\n", name)
	for _, k := range keys {
		fmt.Fprintf(b, "\t%q: {\n", k)
		for _, row := range m[k] {
			fmt.Fprintf(b, "\t\t%q,\n", row)
		}
		b.WriteString("\t},\n")
	}
	b.WriteString("}\n\n")
}

// strconv_ quotes a map key, escaping the '#' key which cannot be a raw ident.
func strconv_(s string) string {
	return fmt.Sprintf("%q", s)
}

var _ = strings.TrimSpace // keep strings import if generator grows

func fatalf(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "gen-sprites: "+format+"\n", args...)
	os.Exit(1)
}
